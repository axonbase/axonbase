    private static volatile String currentLang = "pt-BR";

    private Messages() {}

    /** Set the current language (e.g., "pt-BR", "en"). */
    public static void setLanguage(String lang) {
        if (lang == null || lang.isBlank()) return;
        String normalized = lang.equals("en") || lang.equals("en-US") || lang.equals("en-GB") ? "en" : "pt-BR";
        currentLang = normalized;
    }

    /** Get the current language code. */
    public static String language() { return currentLang; }

    /** Get a formatted message for the current language. */
    public static String get(String key, Object... args) {
        Map<String, String> bundle = BUNDLES.get(currentLang);
        if (bundle == null) bundle = PT_BR;
        String msg = bundle.get(key);
        if (msg == null) return key;
        return args.length > 0 ? String.format(msg, args) : msg;
    }

    /** Get a message for a specific language without changing the global setting. */
    public static String getForLanguage(String lang, String key, Object... args) {
        Map<String, String> bundle = BUNDLES.get(lang.equals("en") ? "en" : "pt-BR");
        if (bundle == null) bundle = PT_BR;
        String msg = bundle.get(key);
        if (msg == null) return key;
        return args.length > 0 ? String.format(msg, args) : msg;
    }
